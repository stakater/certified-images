#!/usr/bin/env bash
# Record the dependency patch in image.yaml (ADR-002 rule 2):
#   scripts/update-deviations.sh images/<name> "<fixed IDs, space separated>" "<bumps, one per line>"
#
# Keeps one deviation for patches/0001-bump-vulnerable-go-modules.patch. The
# IDs it fixes accumulate; the bumps are replaced, because the patch is
# regenerated in full each time. An existing upstreamPR is kept. Everything
# else in image.yaml, comments included, is left as it is.
set -euo pipefail

# shellcheck source=scripts/lib.sh
. "$(dirname "$0")/lib.sh"

DIR=${1:?usage: update-deviations.sh images/<name> "<ids>" "<bumps>"}
FIXES=${2:?usage: update-deviations.sh images/<name> "<ids>" "<bumps>"}
BUMPS=${3:?usage: update-deviations.sh images/<name> "<ids>" "<bumps>"}
YAML="${DIR%/}/image.yaml"
PATCH=patches/0001-bump-vulnerable-go-modules.patch
REASON="Fixable CRITICAL or HIGH vulnerabilities in Go modules, not yet fixed in the pinned upstream release. Generated by scripts/auto-fix.sh on $(date -u +%Y-%m-%d); drop when an upstream release carries the fixes."

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
# shellcheck disable=SC2016 # $old and $e are yq variables
"$ENGINE" run --rm -i -e P="$PATCH" -e REASON="$REASON" -e FIXES="$FIXES" -e BUMPS="$BUMPS" "$YQ_IMAGE" '
  (.deviations // []) as $old
  | (($old | map(select(.patch == strenv(P))) | .[0]) // {}) as $e
  | .deviations = (
      ($old | map(select(.patch != strenv(P))))
      + [ {
          "patch": strenv(P),
          "reason": strenv(REASON),
          "fixes": ((($e.fixes // []) + (strenv(FIXES) | split(" "))) | unique),
          "bumps": (strenv(BUMPS) | split("\n")),
          "upstreamPR": ($e.upstreamPR // "none yet")
        } ]
    )
' <"$YAML" >"$tmp"
[ -s "$tmp" ] || {
  echo "update-deviations: could not rewrite $YAML" >&2
  exit 1
}
cat "$tmp" >"$YAML"
echo "update-deviations: recorded $PATCH in $YAML"
